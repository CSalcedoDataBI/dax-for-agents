#!/usr/bin/env python3
"""The on-disk layout of generated/: one Markdown file per category, not one per card.

The plugin directory holds any plugin that ships more than 512 files for a human reviewer,
and every version waits days again. One card per function was 513 of them (479 functions,
34 conceptual pages). Here they become about 19 bundles under `generated/bundles/`.

Nothing about a card changes but where it sits. Each one is copied verbatim between two
markers, so `split(layout(trees)[0]) == trees` byte for byte -- `--check` proves it on the
real tree in CI. The single edit is a link from one card to another, `./abs.md` ->
`./functions-math-and-trig.md#abs`, which `split` reverses; without it the link would point
at a file that no longer exists.

    trees    {"library": {stem: markdown}, "concepts": {stem: markdown}}
             -- what the sync builds, what the validators read, what refresh edits.
    files    {"functions-filter.md": text, ...} -- what lies in generated/bundles/.
    pointers {("library", "calculate"): "functions-filter:587-757", ...}
             -- first and last line of each card, for the catalog's `Ficha` column. An
             agent reads one card with Read offset=587 limit=171, the same single hop as
             opening its old file.

Grouping: a function goes with its `primaryCategory` (empty -> `uncategorized`); every
concept goes in `concepts`. A group over TARGET bytes splits, in stem order, into even
parts named `<group>-1`, `<group>-2`... The bundles go in a NEW directory on purpose: a
stale `library/filter.md` path then fails loudly instead of opening the FILTER category.

    python card_bundles.py --check    # the tree on disk is exactly layout(split(disk))
    python card_bundles.py --explode <generated> <out>   # one file per card, for diffs
"""
import os
import re
import sys

BUNDLES = "bundles"
SUBDIRS = ("library", "concepts")
# 90 % of 256 KiB, the size the directory's validator still opens without a warning.
TARGET = 230 * 1024
# The longest card is 374 lines; a Read of one card never comes near a whole bundle.

_BEGIN = '<a id="{stem}"></a>\n<!-- card: {sub}/{stem}{nonl} -->\n'
_END = "<!-- /card -->\n"
_MARK = re.compile(r'^<a id="([a-z0-9][a-z0-9.-]*)"></a>\n'
                   r"<!-- card: (library|concepts)/([a-z0-9][a-z0-9.-]*)( no-final-newline)? -->\n",
                   re.M)
_PRIMARY = re.compile(r"^primaryCategory:[ \t]*(\S*)[ \t]*$", re.M)

# A link from one card to another, in the three spellings the sync writes.
_LINK = re.compile(r"\]\((\./|\.\./library/|\.\./concepts/)([a-z0-9][a-z0-9.-]*)\.md(#[^)\s\"]*)?\)")
# The same link once bundled. A section anchor cannot stay an anchor -- every card in a
# bundle has its own "Examples" -- so it rides along as the link title.
_BACK = re.compile(r'\]\(\./([a-z0-9-]+)\.md#([a-z0-9][a-z0-9.-]*)(?: "section:([^"]+)")?\)')


def header(name):
    index, sub = (("concepts.md", "concepts") if name.startswith("concepts")
                  else ("catalog.md", "library"))
    return (f"# DAX reference — {name}\n\n"
            f"> Generated by `scripts/dax-reference/sync_query_docs.py` in the repository. **Do not edit by hand, and do not "
            f"read this file whole.** Open one card with the line range in the `Ficha` "
            f"column of `{index}` (`{name}:<first>-<last>` -> Read offset=<first>, "
            f"limit=<last>-<first>+1), or Grep `card: {sub}/<stem>`.\n\n")


def _group_key(sub, card):
    if sub == "concepts":
        return "concepts"
    m = _PRIMARY.search(card.split("\n---", 1)[0])
    return "functions-" + ((m.group(1) if m else "") or "uncategorized")


def group(trees):
    """{bundle name: [(sub, stem), ...]}, deterministic for a given tree."""
    raw = {}
    for sub in SUBDIRS:
        for stem in sorted(trees.get(sub, {})):
            raw.setdefault(_group_key(sub, trees[sub][stem]), []).append((sub, stem))
    out = {}
    for name in sorted(raw):
        members = raw[name]
        sizes = [len(trees[s][t].encode("utf-8")) + 80 for s, t in members]
        parts_needed = -(-sum(sizes) // TARGET)
        goal = sum(sizes) / parts_needed
        parts, cur, size = [], [], 0
        for m, s in zip(members, sizes):
            if cur and (size + s > TARGET or size >= goal):
                parts.append(cur)
                cur, size = [], 0
            cur.append(m)
            size += s
        parts.append(cur)
        for i, part in enumerate(parts):
            out[name if len(parts) == 1 else f"{name}-{i + 1}"] = part
    return out


def _rewrite(card, here, bundle_of):
    def sub(m):
        pre, stem, anchor = m.groups()
        where = here if pre == "./" else pre[3:-1]
        b = bundle_of.get((where, stem))
        if b is None:
            return m.group(0)
        return f"](./{b}.md#{stem}" + (f' "section:{anchor[1:]}"' if anchor else "") + ")"
    return _LINK.sub(sub, card)


def _unrewrite(card, here, sub_of):
    def sub(m):
        b, stem, section = m.groups()
        where = sub_of.get((b, stem))
        if where is None:
            return m.group(0)
        tail = f"#{section})" if section else ")"
        return f"](./{stem}.md{tail}" if where == here else f"](../{where}/{stem}.md{tail}"
    return _BACK.sub(sub, card)


def layout(trees):
    """(files, pointers) for a tree. See the module docstring."""
    groups = group(trees)
    bundle_of = {m: name for name, ms in groups.items() for m in ms}
    files, pointers = {}, {}
    for name, members in groups.items():
        chunks = [header(name)]
        line = header(name).count("\n") + 1
        for sub, stem in members:
            card = _rewrite(trees[sub][stem], sub, bundle_of)
            nl = card.endswith("\n")
            block = (_BEGIN.format(stem=stem, sub=sub, nonl="" if nl else " no-final-newline")
                     + card + ("" if nl else "\n") + _END + "\n")
            last = line + block.count("\n") - 2          # the END marker's line
            pointers[(sub, stem)] = f"{name}:{line}-{last}"
            line += block.count("\n")
            chunks.append(block)
        files[f"{name}.md"] = "".join(chunks)
    return files, pointers


def split(files):
    """The tree a set of bundle files holds. Raises ValueError on a malformed bundle."""
    sub_of, found = {}, []
    for fname, text in files.items():
        b = fname[:-3]
        for m in _MARK.finditer(text):
            anchor, sub, stem, nonl = m.groups()
            if anchor != stem:
                raise ValueError(f"{fname}: anchor {anchor!r} does not match card {stem!r}")
            end = text.find(_END, m.end())
            if end < 0:
                raise ValueError(f"{fname}: card {sub}/{stem} has no end marker")
            body = text[m.end():end]
            if nonl:
                if not body.endswith("\n"):
                    raise ValueError(f"{fname}: card {sub}/{stem} lost its added newline")
                body = body[:-1]
            sub_of[(b, stem)] = sub
            found.append((b, sub, stem, body))
    trees = {s: {} for s in SUBDIRS}
    for b, sub, stem, body in found:
        if stem in trees[sub]:
            raise ValueError(f"card {sub}/{stem} appears in more than one bundle")
        trees[sub][stem] = _unrewrite(body, sub, sub_of)
    return trees


def read_files(generated):
    d = os.path.join(generated, BUNDLES)
    if not os.path.isdir(d):
        return {}
    out = {}
    for name in sorted(os.listdir(d)):
        if name.endswith(".md"):
            with open(os.path.join(d, name), encoding="utf-8") as f:
                out[name] = f.read()
    return out


def read(generated):
    """The tree under `generated/`. Empty subtrees when nothing has been built yet."""
    return split(read_files(generated))


def write(generated, files):
    """Replace generated/bundles/ with `files`. Stale bundles are removed."""
    d = os.path.join(generated, BUNDLES)
    os.makedirs(d, exist_ok=True)
    for name in os.listdir(d):
        if name.endswith(".md") and name not in files:
            os.remove(os.path.join(d, name))
    for name, text in files.items():
        with open(os.path.join(d, name), "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


def pointers_for(pointers, sub):
    """{stem: "bundle:first-last"} for one subtree, the shape the catalog renderers take."""
    return {stem: p for (s, stem), p in pointers.items() if s == sub}


def save(generated, trees):
    """Write `trees` as bundles under `generated/`. Returns the pointers of the new layout."""
    files, pointers = layout(trees)
    write(generated, files)
    return pointers


def pointers_on_disk(generated):
    return layout(read(generated))[1]


def check(generated):
    """Problems with the tree on disk, as sentences. Empty means it is exactly canonical."""
    problems = [f"generated/{sub}/ is the one-file-per-card layout — the cards live in "
                f"generated/{BUNDLES}/ now; delete it" for sub in SUBDIRS
                if os.path.isdir(os.path.join(generated, sub))]
    on_disk = read_files(generated)
    if not on_disk:
        return problems
    try:
        trees = split(on_disk)
    except ValueError as exc:
        return problems + [str(exc)]
    expected, _ = layout(trees)
    for name in sorted(set(on_disk) | set(expected)):
        if on_disk.get(name) != expected.get(name):
            problems.append(f"bundles/{name} is not what layout(split(...)) writes — "
                            f"regenerate it, never edit a bundle by hand")
    return problems


def explode(generated, out):
    """Write the tree one file per card under `out/{library,concepts}/`, plus the indexes.

    For reading a change card by card: the weekly sync diffs two exploded trees, so its
    pull request still names the function that changed instead of a whole bundle."""
    import shutil
    for sub, cards in read(generated).items():
        d = os.path.join(out, sub)
        os.makedirs(d, exist_ok=True)
        for stem, text in cards.items():
            with open(os.path.join(d, f"{stem}.md"), "w", encoding="utf-8", newline="\n") as f:
                f.write(text)
    for name in ("catalog.md", "concepts.md", "catalog.json"):
        if os.path.exists(os.path.join(generated, name)):
            shutil.copyfile(os.path.join(generated, name), os.path.join(out, name))


def main(argv):
    if len(argv) == 3 and argv[0] == "--explode":
        explode(argv[1], argv[2])
        return 0
    if argv != ["--check"]:
        print(__doc__)
        return 2
    here = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))), "plugins", "dax-for-agents", "skills", "dax-reference")
    problems = check(os.path.join(here, "generated"))
    for p in problems:
        print(f"FAIL: {p}")
    if problems:
        return 1
    trees = read(os.path.join(here, "generated"))
    print(f"OK: {sum(len(v) for v in trees.values())} cards in "
          f"{len(read_files(os.path.join(here, 'generated')))} bundles, and each one splits "
          f"back and rebuilds to the same bytes.")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
